"use strict";

const { validateUnifiedDiff } = require("./patch-candidate");

const SHA_RE = /^[0-9a-f]{40}$/i;
const BRANCH_RE = /^samurai\/repair-[a-f0-9-]{8,80}$/;
const MAX_FILES = 20;

function requireProof(proof = {}) {
  if (proof.passed !== true) throw new Error("VERIFIED_REPRODUCTION_REQUIRED");
  if (proof.reproduction !== true) throw new Error("REPRODUCTION_REQUIRED");
  if (proof.causality !== true) throw new Error("CAUSALITY_REQUIRED");
}

function branchName(jobId, baseSha) {
  const raw = String(jobId || "").toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  const suffix = String(baseSha || "").slice(0, 12).toLowerCase();
  const name = "samurai/repair-" + (raw || "job").slice(0, 50) + "-" + suffix;
  if (!BRANCH_RE.test(name)) throw new Error("INVALID_REPAIR_BRANCH");
  return name;
}

function validateFinalFiles(files = []) {
  if (!Array.isArray(files) || !files.length) throw new Error("FINAL_FILES_REQUIRED");
  if (files.length > MAX_FILES) throw new Error("TOO_MANY_FINAL_FILES");
  return files.map(file => {
    const path = String(file?.path || "");
    if (!path || path.startsWith("/") || /(^|\/)\.\.\//.test(path) || /^\.env(?:\.|$)/.test(path) || /^\.github\/workflows\//.test(path)) {
      throw new Error("UNSAFE_FINAL_FILE");
    }
    if (typeof file.content !== "string") throw new Error("FINAL_FILE_CONTENT_REQUIRED");
    return { path, content: file.content };
  });
}

async function createRepairPullRequest(input = {}, github = {}) {
  requireProof(input.reproductionProof);
  const baseSha = String(input.baseSha || "");
  if (!SHA_RE.test(baseSha)) throw new Error("EXACT_BASE_SHA_REQUIRED");

  const repository = String(input.repository || "");
  if (!/^[^/]+\/[^/]+$/.test(repository)) throw new Error("INVALID_REPOSITORY");

  const diff = String(input.patchCandidate?.diff || "");
  if (!diff) throw new Error("PATCH_CANDIDATE_REQUIRED");
  validateUnifiedDiff(diff);

  const files = validateFinalFiles(input.finalFiles);
  const createBranch = github.createBranch;
  const createBlob = github.createBlob;
  const createTree = github.createTree;
  const createCommit = github.createCommit;
  const createPullRequest = github.createPullRequest;
  if (![createBranch, createBlob, createTree, createCommit, createPullRequest].every(fn => typeof fn === "function")) {
    throw new Error("GITHUB_WRITERS_REQUIRED");
  }

  const branch = branchName(input.jobId, baseSha);
  await createBranch({ repository_full_name: repository, branch_name: branch, sha: baseSha });

  const blobs = [];
  for (const file of files) {
    const blob = await createBlob({ repository_full_name: repository, content: file.content, encoding: "utf-8" });
    const sha = blob?.result?.sha;
    if (!SHA_RE.test(String(sha || ""))) throw new Error("INVALID_BLOB_SHA");
    blobs.push({ path: file.path, mode: "100644", type: "blob", sha });
  }

  const tree = await createTree({
    repository_full_name: repository,
    tree_elements: blobs,
    base_tree_sha: baseSha
  });
  const treeSha = tree?.result?.sha;
  if (!SHA_RE.test(String(treeSha || ""))) throw new Error("INVALID_TREE_SHA");

  const commit = await createCommit({
    repository_full_name: repository,
    message: "fix: verified CI repair",
    tree_sha: treeSha,
    parent_sha: baseSha
  });
  const commitSha = commit?.result?.sha;
  if (!SHA_RE.test(String(commitSha || ""))) throw new Error("INVALID_COMMIT_SHA");

  const pr = await createPullRequest({
    repository_full_name: repository,
    title: "fix: verified CI repair",
    body: "Generated by SAMURAI CI Rescue. Reproduction and causality gates passed. Merge is intentionally not automated.",
    head: branch,
    base: String(input.baseBranch || "main"),
    draft: false,
    maintainer_can_modify: false
  });

  return {
    branch,
    commitSha,
    pr: pr?.result || null,
    autonomousMerge: false,
    verifiedBeforePR: true
  };
}

module.exports = { createRepairPullRequest, branchName, validateFinalFiles, requireProof };
