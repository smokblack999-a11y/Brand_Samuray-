"use strict";

const { createGithubPrAdapter } = require("./github-pr-adapter");

function sleep(ms) { return new Promise(resolve => setTimeout(resolve, ms)); }

function createLiveGithubPrAdapter({
  github, sandboxWorkflow = "core.yml", pollMs = 5000, timeoutMs = 120000
} = {}) {
  if (!github) throw new TypeError("github is required");

  return createGithubPrAdapter({
    create: async ({ mission, execution }) => {
      const run = mission?.input?.workflowRun || mission?.input?.workflow_run || {};
      const base = run?.repository?.default_branch || "main";
      const candidate = execution?.candidate;
      const branch = candidate?.branch;
      const files = Array.isArray(candidate?.files) ? candidate.files : [];
      if (!branch || !files.length) throw new Error("candidate_branch_and_files_required");

      await github.createBranch({ branch, from: base });
      for (const file of files) {
        if (!file?.path || typeof file.content !== "string") throw new Error("invalid_candidate_file");
        await github.upsertFile({
          branch, path: file.path, content: file.content,
          message: candidate.commit_message || "x29: bounded repair"
        });
      }

      const started = Date.now();
      let sandboxRun = null;
      while (Date.now() - started < timeoutMs) {
        const result = await github.listWorkflowRuns({ branch, event: "push", perPage: 20 });
        const runs = Array.isArray(result?.workflow_runs) ? result.workflow_runs : [];
        sandboxRun = runs.find(item => String(item?.path || "").includes(sandboxWorkflow)) || runs[0] || null;
        if (sandboxRun?.status === "completed") break;
        await sleep(pollMs);
      }

      if (!sandboxRun || sandboxRun.status !== "completed") {
        throw new Error("sandbox_ci_timeout");
      }
      if (sandboxRun.conclusion !== "success") {
        const error = new Error("sandbox_ci_failed");
        error.sandboxRun = { id: sandboxRun.id, conclusion: sandboxRun.conclusion, html_url: sandboxRun.html_url };
        throw error;
      }

      const result = await github.createPullRequest({
        title: candidate.title || "x29: automated repair",
        head: branch, base, draft: true,
        body: [
          "Generated by bounded X29 repair runtime.", "",
          "Kill Critic: ALLOW", "GitHub Actions sandbox: PASS",
          `Sandbox run: ${sandboxRun.id}`,
          `Source workflow run: ${run?.id || "unknown"}`
        ].join("\n")
      });
      return { ...result, branch, base, sandboxRun };
    }
  });
}

module.exports = { createLiveGithubPrAdapter };
