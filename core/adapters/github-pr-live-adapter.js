"use strict";

const { createGithubPrAdapter } = require("./github-pr-adapter");

function createLiveGithubPrAdapter({ github } = {}) {
  if (!github) throw new TypeError("github is required");

  return createGithubPrAdapter({
    create: async ({ mission, execution }) => {
      if (execution?.testResult?.passed !== true) {
        throw new Error("pr_requires_sandbox_pass");
      }

      const run = mission?.input?.workflowRun || mission?.input?.workflow_run || {};
      const base = execution?.testResult?.base || run?.repository?.default_branch || "main";
      const branch = execution?.testResult?.branch || execution?.candidate?.branch;
      if (!branch) throw new Error("candidate_branch_required");

      const result = await github.createPullRequest({
        title: execution?.candidate?.title || "x29: automated repair",
        head: branch,
        base,
        draft: true,
        body: [
          "Generated by bounded X29 repair runtime.",
          "",
          "Kill Critic: ALLOW",
          "GitHub Actions sandbox: PASS",
          `Sandbox run: ${execution.testResult?.run?.id || "unknown"}`,
          `Source workflow run: ${run?.id || "unknown"}`
        ].join("\n")
      });

      return { ...result, branch, base, sandboxRun: execution.testResult.run || null };
    }
  });
}

module.exports = { createLiveGithubPrAdapter };
