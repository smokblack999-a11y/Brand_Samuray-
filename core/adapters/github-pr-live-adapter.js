"use strict";

const { createGithubPrAdapter } = require("./github-pr-adapter");

function createLiveGithubPrAdapter({ github }) {
  if (!github) throw new TypeError("github is required");
  return createGithubPrAdapter({
    create: async ({ mission, execution }) => {
      const run = mission?.input?.workflowRun || mission?.input?.workflow_run || {};
      const base = run?.repository?.default_branch || "main";
      const candidate = execution?.candidate;
      const branch = candidate?.branch;
      const files = Array.isArray(candidate?.files) ? candidate.files : [];
      if (!branch || !files.length) throw new Error("candidate_branch_and_files_required");
      await github.createBranch({ branch, from: base });
      for (const file of files) {
        if (!file?.path || typeof file.content !== "string") throw new Error("invalid_candidate_file");
        await github.upsertFile({ branch, path: file.path, content: file.content, message: candidate.commit_message || "x29: bounded repair" });
      }
      const result = await github.createPullRequest({
        title: candidate.title || "x29: automated repair",
        head: branch, base, draft: true,
        body: ["Generated by bounded X29 repair runtime.", "", "Kill Critic: ALLOW", "Sandbox proof: PASS", `Source workflow run: ${run?.id || "unknown"}`].join("\n")
      });
      return { ...result, branch, base };
    }
  });
}

module.exports = { createLiveGithubPrAdapter };
